/*
 * MT6853 MMSYS routing data.
 *
 * The register offsets and selection values were independently compared with
 * the MT6853 implementation in:
 *   OnePlusOSS/android_kernel_oneplus_mt6893
 *   ref 48f1797695e24d46986a7c87dd91dd21cbf8c342
 *   drivers/gpu/drm/mediatek/mtk_drm_ddp.c
 *
 * This is a new ACK mmsys route-table adaptation, not a copied vendor driver.
 * The source attribution is retained because the vendor table is the
 * authoritative public reference for these MT6853 register selections.
 */

#ifndef __MT6853_MMSYS_H
#define __MT6853_MMSYS_H

#include "mtk-mmsys.h"

/*
 * OVL_CON tells each overlay engine whether its output is the final blend
 * (feeds the next display module) or the background of the other overlay.
 * The bootloader leaves it configured for its own cascaded OVL0_2L -> OVL0
 * path, which stalls a standalone OVL0.
 */
#define MT6853_MMSYS_OVL_CON			0x0f04
#define MT6853_MMSYS_OVL_CON_MASK		GENMASK(3, 0)
#define MT6853_MMSYS_OVL0_GO_BLEND		BIT(0)
#define MT6853_MMSYS_OVL0_2L_GO_BLEND		BIT(2)

#define MT6853_MMSYS_TOVL0_OUT0_MOUT_EN	0x0f14
#define MT6853_MMSYS_TOVL0_OUT1_MOUT_EN	0x0f18
#define MT6853_MMSYS_RDMA0_SEL_IN		0x0f28
#define MT6853_MMSYS_WDMA0_SEL_IN		0x0f34
#define MT6853_MMSYS_RDMA0_RSZ0_SOUT_SEL	0x0f0c
#define MT6853_MMSYS_DSI0_SEL_IN		0x0f30

#define MT6853_MMSYS_OVL0_2L_TO_RDMA0		BIT(0)
#define MT6853_MMSYS_OVL0_2L_TO_WDMA0		BIT(2)
#define MT6853_MMSYS_OVL0_TO_RDMA0		BIT(0)
#define MT6853_MMSYS_OVL0_TO_WDMA0		BIT(2)
#define MT6853_MMSYS_RDMA0_SEL_MASK		0x00000007
#define MT6853_MMSYS_RDMA0_FROM_OVL0		0x00000000
#define MT6853_MMSYS_RDMA0_FROM_OVL0_2L		0x00000002
#define MT6853_MMSYS_WDMA0_SEL_MASK		0x00000007
#define MT6853_MMSYS_WDMA0_FROM_OVL0		0x00000003
#define MT6853_MMSYS_WDMA0_FROM_OVL0_2L		0x00000002
#define MT6853_MMSYS_RDMA0_RSZ0_SOUT_SEL_MASK	0x00000007
#define MT6853_MMSYS_RDMA0_RSZ0_SOUT_TO_DSI0	0x00000000
#define MT6853_MMSYS_DSI0_SEL_IN_MASK		0x00000007
#define MT6853_MMSYS_DSI0_FROM_RDMA0_RSZ0_SOUT	0x00000000

static const struct mtk_mmsys_routes mt6853_mmsys_routing_table[] = {
	MMSYS_ROUTE(OVL_2L0, RDMA0, MT6853_MMSYS_TOVL0_OUT0_MOUT_EN,
		    MT6853_MMSYS_OVL0_2L_TO_RDMA0,
		    MT6853_MMSYS_OVL0_2L_TO_RDMA0),
	MMSYS_ROUTE(OVL_2L0, WDMA0, MT6853_MMSYS_TOVL0_OUT0_MOUT_EN,
		    MT6853_MMSYS_OVL0_2L_TO_WDMA0,
		    MT6853_MMSYS_OVL0_2L_TO_WDMA0),
	MMSYS_ROUTE(OVL0, RDMA0, MT6853_MMSYS_TOVL0_OUT1_MOUT_EN,
		    MT6853_MMSYS_OVL0_TO_RDMA0,
		    MT6853_MMSYS_OVL0_TO_RDMA0),
	MMSYS_ROUTE(OVL0, WDMA0, MT6853_MMSYS_TOVL0_OUT1_MOUT_EN,
		    MT6853_MMSYS_OVL0_TO_WDMA0,
		    MT6853_MMSYS_OVL0_TO_WDMA0),
	MMSYS_ROUTE(OVL0, RDMA0, MT6853_MMSYS_OVL_CON,
		    MT6853_MMSYS_OVL_CON_MASK, MT6853_MMSYS_OVL0_GO_BLEND),
	MMSYS_ROUTE(OVL_2L0, RDMA0, MT6853_MMSYS_OVL_CON,
		    MT6853_MMSYS_OVL_CON_MASK, MT6853_MMSYS_OVL0_2L_GO_BLEND),
	MMSYS_ROUTE(OVL0, RDMA0, MT6853_MMSYS_RDMA0_SEL_IN,
		    MT6853_MMSYS_RDMA0_SEL_MASK, MT6853_MMSYS_RDMA0_FROM_OVL0),
	MMSYS_ROUTE(OVL_2L0, RDMA0, MT6853_MMSYS_RDMA0_SEL_IN,
		    MT6853_MMSYS_RDMA0_SEL_MASK, MT6853_MMSYS_RDMA0_FROM_OVL0_2L),
	MMSYS_ROUTE(OVL0, WDMA0, MT6853_MMSYS_WDMA0_SEL_IN,
		    MT6853_MMSYS_WDMA0_SEL_MASK, MT6853_MMSYS_WDMA0_FROM_OVL0),
	MMSYS_ROUTE(OVL_2L0, WDMA0, MT6853_MMSYS_WDMA0_SEL_IN,
		    MT6853_MMSYS_WDMA0_SEL_MASK, MT6853_MMSYS_WDMA0_FROM_OVL0_2L),
	MMSYS_ROUTE(RDMA0, DSI0, MT6853_MMSYS_RDMA0_RSZ0_SOUT_SEL,
		    MT6853_MMSYS_RDMA0_RSZ0_SOUT_SEL_MASK,
		    MT6853_MMSYS_RDMA0_RSZ0_SOUT_TO_DSI0),
	MMSYS_ROUTE(RDMA0, DSI0, MT6853_MMSYS_DSI0_SEL_IN,
		    MT6853_MMSYS_DSI0_SEL_IN_MASK,
		    MT6853_MMSYS_DSI0_FROM_RDMA0_RSZ0_SOUT),
};

#endif
